/**
 * Writes referee/data/poker/preflop-chart.json: 169 hand classes → action per spot.
 * Run: npx tsx src/poker/gen-chart.ts
 *
 * The thresholds follow common heads-up limit opening ranges: the button (small blind) raises
 * roughly the top 70% of hands and limps a few more, the big blind defends most hands against a
 * single raise (it already has half the bet in) and 3-bets the top ~15%, and the button continues
 * against a 3-bet with the top ~45%. Hands are ordered by the Chen formula, a standard quick
 * strength score, so each range is "Chen score at or above a cut".
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { allHandClasses, chenScore } from "./bots/common.js";

type A = "raise" | "call" | "fold";
const spots: Record<string, (c: number) => A> = {
  button_open: (c) => (c >= 3 ? "raise" : c >= 1 ? "call" : "fold"),
  bb_vs_limp: (c) => (c >= 7 ? "raise" : "call"),
  bb_vs_raise: (c) => (c >= 9 ? "raise" : c >= 1 ? "call" : "fold"),
  button_vs_3bet: (c) => (c >= 11 ? "raise" : c >= 4 ? "call" : "fold"),
};

const hands = allHandClasses();
const chart: Record<string, Record<string, A>> = {};
for (const [spot, f] of Object.entries(spots)) {
  chart[spot] = Object.fromEntries(hands.map((h) => [h, f(chenScore(h))]));
}
const out = {
  name: "BotBet heads-up limit Hold'em preflop chart",
  hands: hands.length,
  spots: Object.keys(spots),
  notes: "call in bb_vs_limp means check. Generated by referee/src/poker/gen-chart.ts from Chen-score cuts approximating standard HU-LHE ranges.",
  chart,
};
const path = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "data", "poker", "preflop-chart.json");
mkdirSync(dirname(path), { recursive: true });
writeFileSync(path, JSON.stringify(out, null, 1) + "\n");
const share = (spot: string, a: A) => Object.values(chart[spot]!).filter((x) => x === a).length;
for (const s of Object.keys(spots)) console.log(s, "raise", share(s, "raise"), "call", share(s, "call"), "fold", share(s, "fold"));
console.log("wrote", path);
